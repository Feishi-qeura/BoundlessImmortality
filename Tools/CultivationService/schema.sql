PRAGMA journal_mode=WAL;
PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS schema_version(version INTEGER PRIMARY KEY);
INSERT OR IGNORE INTO schema_version VALUES(1);
CREATE TABLE IF NOT EXISTS namespace(
 id TEXT PRIMARY KEY, app TEXT NOT NULL, profile TEXT NOT NULL, rules TEXT NOT NULL,
 rules_hash TEXT NOT NULL, start REAL NOT NULL, end REAL NOT NULL, version INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS identity(
 scope TEXT NOT NULL, user TEXT NOT NULL, role TEXT NOT NULL, name TEXT NOT NULL,
 PRIMARY KEY(scope,user));
CREATE TABLE IF NOT EXISTS session(
 token TEXT PRIMARY KEY, scope TEXT NOT NULL, user TEXT NOT NULL, room TEXT NOT NULL,
 generation INTEGER NOT NULL, active INTEGER NOT NULL DEFAULT 0,
 heartbeat REAL NOT NULL, revoked INTEGER NOT NULL DEFAULT 0);
CREATE UNIQUE INDEX IF NOT EXISTS current_session ON session(scope,user) WHERE revoked=0;
CREATE TABLE IF NOT EXISTS growth(
 scope TEXT NOT NULL, user TEXT NOT NULL, realm INTEGER NOT NULL DEFAULT 0,
 qi REAL NOT NULL DEFAULT 0, total REAL NOT NULL DEFAULT 0,
 cursor REAL NOT NULL, offline_seconds REAL NOT NULL DEFAULT 0,
 PRIMARY KEY(scope,user));
CREATE TABLE IF NOT EXISTS guild(
 scope TEXT NOT NULL, id TEXT NOT NULL, anchor TEXT NOT NULL, name TEXT NOT NULL,
 created REAL NOT NULL, renamed REAL NOT NULL, dissolved INTEGER NOT NULL DEFAULT 0,
 PRIMARY KEY(scope,id));
CREATE UNIQUE INDEX IF NOT EXISTS anchor_guild ON guild(scope,anchor) WHERE dissolved=0;
CREATE TABLE IF NOT EXISTS membership(
 scope TEXT NOT NULL, user TEXT NOT NULL, guild_id TEXT, joined REAL NOT NULL DEFAULT 0,
 rejoin_after REAL NOT NULL DEFAULT 0, PRIMARY KEY(scope,user));
CREATE TABLE IF NOT EXISTS wallet(
 scope TEXT NOT NULL, owner TEXT NOT NULL, currency TEXT NOT NULL, amount INTEGER NOT NULL CHECK(amount>=0),
 PRIMARY KEY(scope,owner,currency));
CREATE TABLE IF NOT EXISTS wallet_ledger(
 id TEXT PRIMARY KEY, scope TEXT NOT NULL, owner TEXT NOT NULL, currency TEXT NOT NULL,
 amount INTEGER NOT NULL, reason TEXT NOT NULL, source TEXT NOT NULL, created REAL NOT NULL);
CREATE TABLE IF NOT EXISTS item_instance(
 id TEXT PRIMARY KEY, scope TEXT NOT NULL, owner TEXT NOT NULL, item TEXT NOT NULL,
 count INTEGER NOT NULL CHECK(count>=0), binding TEXT NOT NULL, paid INTEGER NOT NULL DEFAULT 0,
 created REAL NOT NULL, expiry REAL NOT NULL, source TEXT NOT NULL, reserved TEXT,
 version INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS entity(
 scope TEXT NOT NULL, kind TEXT NOT NULL, id TEXT NOT NULL, data TEXT NOT NULL,
 PRIMARY KEY(scope,kind,id));
CREATE TABLE IF NOT EXISTS fact(
 scope TEXT NOT NULL, id TEXT NOT NULL, kind TEXT NOT NULL, user TEXT NOT NULL,
 created REAL NOT NULL, data TEXT NOT NULL, PRIMARY KEY(scope,id));
CREATE TABLE IF NOT EXISTS command_receipt(
 scope TEXT NOT NULL, user TEXT NOT NULL, request TEXT NOT NULL, payload_hash TEXT NOT NULL,
 result TEXT NOT NULL, created REAL NOT NULL, PRIMARY KEY(scope,user,request));
CREATE TABLE IF NOT EXISTS counter(
 scope TEXT NOT NULL, owner TEXT NOT NULL, key TEXT NOT NULL, value INTEGER NOT NULL,
 PRIMARY KEY(scope,owner,key));
CREATE TABLE IF NOT EXISTS item_ledger(
 id TEXT PRIMARY KEY, scope TEXT NOT NULL, owner TEXT NOT NULL, item TEXT NOT NULL,
 amount INTEGER NOT NULL, paid INTEGER NOT NULL, created REAL NOT NULL);
CREATE TABLE IF NOT EXISTS visit(
 scope TEXT NOT NULL, user TEXT NOT NULL, day TEXT NOT NULL,
 created REAL NOT NULL, PRIMARY KEY(scope,user,day));
